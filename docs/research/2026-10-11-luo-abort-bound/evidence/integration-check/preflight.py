def digest(data):
    return hashlib.sha256(data).hexdigest()


def git(repo, *args):
    return subprocess.check_output(["git", "-C", str(repo), *args], timeout=20).decode("utf-8").strip()


def public_surface(path):
    """Only public names/signatures/docstrings and import provenance; no execution."""
    raw = path.read_bytes()
    tree = ast.parse(raw.decode("utf-8-sig"), filename=str(path))
    classes, functions, imports = [], [], []
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            imports.append(ast.unparse(node))
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
            functions.append({"name": node.name, "line": node.lineno, "signature": ast.unparse(node.args)})
        if isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            methods = [{"name": f.name, "line": f.lineno, "signature": ast.unparse(f.args)}
                       for f in node.body if isinstance(f, (ast.FunctionDef, ast.AsyncFunctionDef))
                       and not f.name.startswith("_")]
            classes.append({"name": node.name, "line": node.lineno,
                            "bases": [ast.unparse(b) for b in node.bases], "methods": methods})
    return {"sha256": digest(raw), "bytes": len(raw), "module_doc": ast.get_docstring(tree),
            "classes": classes, "functions": functions, "imports": imports}


def source_snapshot(repo):
    """Pin helpers as well as the slot; a changed helper invalidates a review."""
    files = {}
    for directory in (repo / "src/ibme", repo / "experiments/research"):
        if not directory.is_dir():
            raise ValueError("missing required source directory: " + str(directory))
        for path in sorted(directory.rglob("*.py")):
            if path.is_symlink() or not path.resolve().is_relative_to(repo.resolve()):
                raise ValueError("source link escapes the audited repository")
            files[path.relative_to(repo).as_posix()] = digest(path.read_bytes())
    encoded = json.dumps(files, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return {"sha256": digest(encoded), "files": files}


def contract_problems(record):
    """Review semantics only. No name, self-declared admission flag, or cap8 sum."""
    if not isinstance(record, dict) or set(record) != set(CONTRACT):
        return ["FUNCTIONAL_CONTRACT_FIELDS_MISSING_OR_UNKNOWN"]
    errors = []
    for key, expected in CONTRACT.items():
        observed = record[key]
        if key == "same_leaf_target_capacity":
            valid = type(observed) is int and observed >= 256
        elif key == "position_range":
            valid = type(observed) is list and observed == expected and all(type(x) is int for x in observed)
        else:
            valid = type(observed) is type(expected) and observed == expected
        if not valid:
            errors.append("CONTRACT_MISMATCH:" + key)
    return errors


def teaching_imports(surface):
    """Catch direct teaching delegates/aliases even if a class is renamed CHKP."""
    return [line for line in surface["imports"]
            if any(token in line.lower() for token in ("abb10", "mockhibe", "hibe.mock"))]


def backend_problems(backend, repo):
    """Inspect public bound methods; never touch key fields, matrices, or RNG.

    Only the actual slot class and slot-defined entry methods are eligible.
    Aliases, subclasses of ABB10/Mock, inherited teaching methods, forwarding
    proxies, instances with monkeypatched methods and unknown wrappers fail.
    Source semantics still require the main integrator's explicit review.
    """
    errors = []
    cls = type(backend)
    for base in inspect.getmro(cls):
        tag = (base.__module__ + "." + base.__name__).lower()
        if any(word in tag for word in ("mock", "abb10", "teaching", "fixture", "recordinginner")):
            errors.append("MOCK_OR_TEACHING_BACKEND")
    try:
        origin = Path(inspect.getfile(cls)).resolve()
    except (TypeError, OSError):
        origin = None
    if cls.__module__ != "ibme.hibe.chkp" or origin != (repo / SLOT).resolve():
        errors.append("NOT_THE_REVIEWED_CHKP_SLOT")
    for method, arguments in METHOD_ARGS.items():
        value = getattr(backend, method, None)
        if not inspect.ismethod(value) or value.__self__ is not backend:
            errors.append("MISSING_OR_REPLACED_PUBLIC_METHOD:" + method)
            continue
        if Path(inspect.getfile(value)).resolve() != (repo / SLOT).resolve():
            errors.append("UNREVIEWED_METHOD_ORIGIN:" + method)
        kwargs = {name: object() for name in arguments}
        if method not in ("load_ciphertext", "validate_key_binding"):
            kwargs["rng"] = None
        try:
            inspect.signature(value).bind(**kwargs)
        except TypeError:
            errors.append("PUBLIC_SIGNATURE_MISMATCH:" + method)
    return sorted(set(errors))


def reject_duplicate_keys(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate JSON field: " + key)
        result[key] = value
    return result


def functional_verdict(blockers):
    """Security is deliberately separate from permission to do a functional smoke."""
    return {"functional_status": "BLOCKED" if blockers else "READY_FOR_BOUNDED_SMOKE",
            "ready_for_bounded_smoke": not blockers, "first_blocker": blockers[0] if blockers else None,
            "security_claim": "none", "backend_admitted": False,
            "functional_integration_passed": False, "smoke_executed": False,
            "exit_code": 2 if blockers else 0}


def check(repo, expected_head=EXPECTED_HEAD, review=None):
    repo = Path(repo).resolve()
    result = {"schema": "CODEX/CHKP-LUO-PREFLIGHT/1", "repo": str(repo),
              "functional_status": "BLOCKED", "ready_for_bounded_smoke": False,
              "functional_integration_passed": False, "smoke_executed": False,
              "security_claim": "none", "backend_admitted": False,
              "security_admission": "NOT_EVALUATED_MAIN_OWNER",
              "required_contract": CONTRACT, "blockers": [], "inventory": {}}
    blockers = result["blockers"]
    result["git_head"] = git(repo, "rev-parse", "HEAD")
    result["git_status"] = git(repo, "status", "--porcelain=v1")
    if result["git_head"] != expected_head:
        blockers.append("REPOSITORY_HEAD_MISMATCH")
    # Shared worktrees can contain authorized parallel work. Record status;
    # review the actual source snapshot, not the fiction of a globally clean tree.
    result["source_snapshot"] = source_snapshot(repo)
    for folder in ("src/ibme/hibe", "experiments/research/first_suite"):
        for path in sorted((repo / folder).glob("*.py")):
            result["inventory"][path.relative_to(repo).as_posix()] = public_surface(path)
    slot = repo / SLOT
    if not slot.is_file():
        blockers.append("CHKP_PUBLIC_BACKEND_MISSING")
    else:
        if teaching_imports(result["inventory"][SLOT]):
            blockers.append("MOCK_OR_TEACHING_SLOT_DEPENDENCY")
        if review is None:
            blockers.append("CHKP_FUNCTIONAL_SOURCE_REVIEW_REQUIRED")
    if review is not None and slot.is_file():
        required_fields = {"schema", "git_head", "source_snapshot_sha256", "backend_class", "parameter_object",
                           "component_classes", "contract", "review_evidence"}
        if (not isinstance(review, dict) or set(review) != required_fields
                or review.get("schema") != "CHKP-FUNCTIONAL-SLOT-REVIEW/1"):
            blockers.append("INVALID_FUNCTIONAL_REVIEW_SCHEMA")
        else:
            if review["git_head"] != result["git_head"] or review["source_snapshot_sha256"] != result["source_snapshot"]["sha256"]:
                blockers.append("STALE_FUNCTIONAL_REVIEW")
            if not isinstance(review["review_evidence"], str) or not review["review_evidence"].strip():
                blockers.append("MISSING_FUNCTIONAL_REVIEW_EVIDENCE")
            blockers.extend(contract_problems(review["contract"]))
            components = review["component_classes"]
            if not isinstance(components, dict) or set(components) != {"public_key", "master", "level1", "level2"}:
                blockers.append("MISSING_PUBLIC_COMPONENT_DECODERS")
            if not isinstance(review["backend_class"], str) or not review["backend_class"].isidentifier():
                blockers.append("INVALID_BACKEND_CLASS_NAME")
            if not isinstance(review["parameter_object"], str) or not review["parameter_object"].isidentifier():
                blockers.append("INVALID_PARAMETER_OBJECT_NAME")
            if not blockers:
                # Candidate imports are opt-in through an exact source review.
                # Launch this CLI under the bounded evidence runner. Imports and
                # constructors may execute code; unreviewed candidates never run.
                sys.path[:0] = [str(repo / "src"), str(repo)]
                module = importlib.import_module("ibme.hibe.chkp")
                cls = getattr(module, review["backend_class"])
                backend = cls()
                blockers.extend(backend_problems(backend, repo))
                params = getattr(module, review["parameter_object"])
                from ibme.protocol.hybrid_hibe import HybridHIBEParams, HybridLimits
                # Public configuration only; none/false is allowed for a smoke.
                try:
                    if type(params.identity_bytes) is not int or type(params.max_message_bytes) is not int:
                        raise ValueError("parameter capacities must be integers")
                    HybridHIBEParams(params, HybridLimits(backend_id=b"chkp-rom-research"))
                except Exception:
                    blockers.append("HYBRID_PARAMETER_CONTRACT_MISMATCH")
                for role, name in components.items():
                    value = getattr(module, name, None) if isinstance(name, str) else None
                    if not inspect.isclass(value) or any(not callable(getattr(value, op, None)) for op in ("from_bytes", "to_bytes")):
                        blockers.append("INVALID_PUBLIC_COMPONENT_DECODER:" + role)
                        continue
                    if Path(inspect.getfile(value)).resolve() != slot.resolve():
                        blockers.append("UNREVIEWED_COMPONENT_ORIGIN:" + role)
                    try:
                        inspect.signature(value.from_bytes).bind(b"")
                    except TypeError:
                        blockers.append("UNBOUND_COMPONENT_DECODER:" + role)
                if source_snapshot(repo) != result["source_snapshot"]:
                    blockers.append("SOURCE_CHANGED_DURING_PREFLIGHT")
    result.update(functional_verdict(blockers))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=DEFAULT_REPO)
    parser.add_argument("--expected-head", default=EXPECTED_HEAD)
    parser.add_argument("--functional-review", type=Path,
                        help="optional main-reviewed source-bound CHKP functional record, NOT a security certificate")
    args = parser.parse_args()
    try:
        review = (json.loads(args.functional_review.read_text(encoding="utf-8-sig"), object_pairs_hook=reject_duplicate_keys)
                  if args.functional_review else None)
        result = check(args.repo, args.expected_head, review)
    except Exception as exc:
        result = {"functional_status": "ERROR", "first_blocker": "PREFLIGHT_ERROR",
                  "error_type": type(exc).__name__, "ready_for_bounded_smoke": False,
                  "functional_integration_passed": False, "smoke_executed": False,
                  "security_claim": "none", "backend_admitted": False, "exit_code": 3}
    print(json.dumps(result, ensure_ascii=True, indent=2))
    return result["exit_code"]


if __name__ == "__main__":
    raise SystemExit(main())
