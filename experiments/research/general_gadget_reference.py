"""MP12 general-q gadget reference using exact randomized nearest-plane sampling.

Research only. All possible rational center residue classes are certified before
sampling. The resulting precomputation is intentionally bounded and is not an
efficient sampler for formal large-modulus parameters. No full SamplePre/backend.
Run in WSL conda ~/miniconda3/envs/sage with PYTHONPATH=src.
"""

