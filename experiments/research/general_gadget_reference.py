def _integer(value, name, *, minimum=0, maximum=None):
    if isinstance(value, bool) or not isinstance(value, (int, type(ZZ(0)))):
        raise ValueError(f"{name} must be an integer")
    result = int(value)
    if result < minimum or (maximum is not None and result > maximum):
        raise ValueError(f"{name} is outside the reference resource range")
    return result


def _exact_rational(value, name):
    if isinstance(value, bool) or not isinstance(value,
            (str, int, Fraction, type(QQ(0)), type(ZZ(0)))):
        raise ValueError(f"{name} requires an exact rational")
    try:
        return QQ(value)
    except (ValueError, TypeError, ZeroDivisionError) as exc:
        raise ValueError(f"Invalid rational {name}") from exc


@dataclass(frozen=True)
class GadgetBasis:
    q: int
    k: int
    order: str
    basis: object
    orthogonal: tuple
    norm_squared: tuple
    mu: tuple
    offset_projection: tuple
    center_denominators: tuple[int, ...]

    def record(self):
        return {"q": self.q, "k": self.k, "basis_order": self.order,
                "basis_columns_stored_in_rows": False,
                "basis_rows": [[int(x) for x in row] for row in self.basis.rows()],
                "determinant_absolute": int(abs(self.basis.det())),
                "gram_schmidt_squared_norms": [str(x) for x in self.norm_squared],
                "center_class_denominators": list(self.center_denominators),
                "center_classes_total": sum(self.center_denominators),
                "security_claim": "none"}


def gadget_basis(q, *, order="forward"):
    """Complete integer kernel basis, with MP12 column order made explicit.

    For nonpowers of two use section 4.2 binary q digits in the last column.
    Powers of two use section 4.1's last column 2*e_(k-1), not k zero q digits.
    Reverse orthogonalization is offered only for the power-of-two cross-check.
    """
    q = _integer(q, "q", minimum=2, maximum=1 << 32)
    k = (q-1).bit_length()
    power_two = q & (q-1) == 0
    if order not in ("forward", "reverse") or (order == "reverse" and not power_two):
        raise ValueError("Reverse order is restricted to power-of-two gadgets")
    basis = matrix(ZZ, k, k)
    for i in range(k-1):
        basis[i, i], basis[i+1, i] = 2, -1
    if power_two:
        basis[k-1, k-1] = 2
    else:
        for i in range(k):
            basis[i, k-1] = (q >> i) & 1
    if order == "reverse":
        basis = matrix(ZZ, [list(basis.column(i)) for i in reversed(range(k))]).transpose()
    assert abs(basis.det()) == q
    assert all(sum((1 << i)*basis[i,j] for i in range(k)) % q == 0 for j in range(k))
    columns = [vector(QQ, basis.column(i)) for i in range(k)]
    orthogonal, norms, mu = [], [], [[QQ(0)]*k for _ in range(k)]
    for j, column in enumerate(columns):
        current = column
        for i in range(j):
            mu[j][i] = column.dot_product(orthogonal[i])/norms[i]
            current = current-mu[j][i]*orthogonal[i]
        norm = current.dot_product(current)
        assert norm > 0
        current.set_immutable()
        orthogonal.append(current)
        norms.append(norm)
    # w = u*e_0 is an integer particular preimage. Every center is generated by
    # this offset and integer later coefficients, so these LCMs cover ALL paths.
    projection = tuple(orthogonal[i][0]/norms[i] for i in range(k))
    denominators = tuple(lcm(int(projection[i].denominator()),
        *(int(mu[j][i].denominator()) for j in range(i+1,k))) for i in range(k))
    basis.set_immutable()
    return GadgetBasis(q, k, order, basis, tuple(orthogonal), tuple(norms),
        tuple(tuple(row) for row in mu), projection, denominators)


@dataclass(frozen=True)
class CenterFamily:
    denominator: int
    tables: object
    normalizer_lower: object
    normalizer_upper: object
    max_scalar_tv: object
    cdf_digest: str

    def record(self, s_squared):
        return {"denominator": self.denominator, "center_classes_checked": len(self.tables),
                "coordinate_s_squared": str(s_squared),
                "infinite_normalizer_lower": str(self.normalizer_lower),
                "infinite_normalizer_upper": str(self.normalizer_upper),
                "partition_ratio_upper": str(self.normalizer_upper/self.normalizer_lower),
                "max_scalar_tv_including_abort": str(self.max_scalar_tv),
                "all_center_cdf_sha256": self.cdf_digest,
                "max_support_count": max(len(t.support) for t in self.tables.values())}


class GeneralModulusGadgetSampler:
    """GPV/Klein recurrence with certified center families, target rho_s(x).

    s_squared is exact; coordinate widths sqrt(s_squared/||b_i*||^2) need not be
    rational. Precompute CDFs, not samples. Actual draws always use fresh entropy.
    """

    def __init__(self, q, s_squared, *, order="forward", max_center_classes=4096,
                 **table_options):
        self.geometry = gadget_basis(q, order=order)
        self.q, self.k = self.geometry.q, self.geometry.k
        self.s_squared = _exact_rational(s_squared, "s_squared")
        if self.s_squared <= 0:
            raise ValueError("s_squared must be positive")
        maximum = _integer(max_center_classes, "max_center_classes", minimum=1, maximum=20000)
        if sum(self.geometry.center_denominators) > maximum:
            raise ValueError("All-center precomputation exceeds max_center_classes; no partial certificate")
        if set(table_options)-{"tail_bits","mass_bits","precision_bits","max_trials","max_radius"}:
            raise ValueError("Only finite-table precision and resource options are supported")
        families = []
        for i, denominator in enumerate(self.geometry.center_denominators):
            width_squared = self.s_squared/self.geometry.norm_squared[i]
            tables = {QQ(j)/denominator: build_gaussian_table_squared(width_squared,
                QQ(j)/denominator, **table_options) for j in range(denominator)}
            lower = min(interval_bounds(t.normalizer)[0] for t in tables.values())
            upper = max(interval_bounds(t.normalizer)[1] for t in tables.values())
            if lower <= 0:
                raise ValueError("All-center normalizer lower bound must be positive")
            digests = [(str(c),t.certificate()["cdf_sha256"]) for c,t in tables.items()]
            digest = sha256(json.dumps(digests,separators=(",",":")).encode()).hexdigest()
            families.append(CenterFamily(denominator, MappingProxyType(tables), lower, upper,
                max(t.tv_upper for t in tables.values()), digest))
        self.families = tuple(families)
        self.max_center_classes = maximum
        self.max_radius = int(table_options.get("max_radius",512))

    def coordinate_table(self, index, syndrome, later_coefficients):
        """Public exact conditional center and translated CDF for an audit path."""
        index = _integer(index, "coordinate index", maximum=self.k-1)
        syndrome = _integer(syndrome, "syndrome", maximum=self.q-1)
        later_coefficients = tuple(later_coefficients)
        if len(later_coefficients) != self.k-index-1:
            raise ValueError("Later coefficient dimensions do not match")
        checked = []
        for x in later_coefficients:
            if isinstance(x,bool) or not isinstance(x,(int,type(ZZ(0)))):
                raise ValueError("Later coefficients must be signed integers")
            checked.append(int(x))
        center = -(syndrome*self.geometry.offset_projection[index] +
            sum((self.geometry.mu[j][index]*checked[j-index-1]
                for j in range(index+1,self.k)), QQ(0)))
        shift = int(center.floor())
        fractional = center-shift
        assert (fractional*self.families[index].denominator).denominator() == 1
        return center, shift, self.families[index].tables[fractional]

    def sample(self, syndrome, *, rng=None):
        syndrome = tuple(syndrome)
        if not 1 <= len(syndrome) <= 128:
            raise ValueError("Syndrome dimension must be between 1 and 128")
        targets = [_integer(x,"syndrome",maximum=self.q-1) for x in syndrome]
        rng = SecureRandom() if rng is None else rng
        out = []
        for target in targets:
            coefficients = [0]*self.k
            for i in reversed(range(self.k)):
                _, shift, table = self.coordinate_table(i,target,coefficients[i+1:])
                coefficients[i] = shift+table.sample(rng=rng)
            result = self.geometry.basis*vector(ZZ,coefficients)
            result[0] += target
            out.extend(int(x) for x in result)
        return tuple(out)

    def certificate(self, dimension=1):
        dimension = _integer(dimension,"dimension",minimum=1,maximum=128)
        ratio = QQ(1)
        for family in self.families:
            ratio *= family.normalizer_upper/family.normalizer_lower
        nearest_plane = min(QQ(1),(ratio**dimension-1)/2)
        scalar = min(QQ(1),dimension*sum((f.max_scalar_tv for f in self.families),QQ(0)))
        total = min(QQ(1),nearest_plane+scalar)
        config = self.families[0].tables[QQ(0)].config_record()
        return {"q":self.q,"n":dimension,"k":self.k,"s_squared":str(self.s_squared),
                "basis_order":self.geometry.order,"scalar_draws_per_vector":dimension*self.k,
                "center_classes_checked":sum(f.denominator for f in self.families),
                "max_center_classes":self.max_center_classes,
                "finite_table_options":{**{key:config[key] for key in
                    ("tail_bits","mass_bits","precision_bits","max_trials")},"max_radius":self.max_radius},
                "ideal_nearest_plane_to_spherical_tv_upper":str(nearest_plane),
                "finite_scalar_composition_tv_upper":str(scalar),
                "tv_upper_including_abort":str(total),
                "tv_upper_display":RealIntervalField(80)(total).str(style="brackets"),
                "uniform_in_syndrome_and_all_integer_paths":True,
                "output_space_includes_abort":True,"constant_time":False,"security_claim":"none",
                "center_families":[f.record(self.s_squared/self.geometry.norm_squared[i])
                                   for i,f in enumerate(self.families)]}


def finite_general_gadget_distribution(sampler, syndrome, *, max_states=100000):
    """Exact rational ideal-ticket PMF for one small block; abort excluded.

    The guard counts visited branch edges; no incomplete PMF is returned.
    This PMF is not the law conditional on all bounded entropy draws surviving.
    """
    syndrome = _integer(syndrome,"syndrome",maximum=sampler.q-1)
    maximum = _integer(max_states,"max_states",minimum=1)
    law, coefficients, visited = {}, [0]*sampler.k, 0

    def visit(i, probability):
        nonlocal visited
        if i < 0:
            result = sampler.geometry.basis*vector(ZZ,coefficients)
            result[0] += syndrome
            key = tuple(int(x) for x in result)
            assert key not in law  # A complete lattice basis gives a unique path.
            law[key] = probability
            return
        _, shift, table = sampler.coordinate_table(i,syndrome,coefficients[i+1:])
        for value, mass in zip(table.support,table.masses):
            if not mass:
                continue
            visited += 1
            if visited > maximum:
                raise ValueError("Enumeration exceeds max_states")
            coefficients[i] = shift+value
            visit(i-1,probability*QQ(mass)/table.total_mass)

    visit(sampler.k-1,QQ(1))
    return law
