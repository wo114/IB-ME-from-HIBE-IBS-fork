"""Lossless optional codec tests; algebra fixtures are not sampled keys.

Real original-parameter production-random lifecycle evidence is generated by
paper_runtime_benchmark. These tests deliberately do not consume entropy.
"""
from dataclasses import replace

import pytest

pytest.importorskip("sage.all", reason="specified WSL Sage required")

from ibme.core.errors import SerializationError
from experiments.research.candidates.srgg import paper_compact as codec
from experiments.research.candidates.srgg.paper_compact_bits import pack, unpack
from experiments.research.candidates.srgg.paper_algebra import PaperRing, public_matrix
from experiments.research.candidates.srgg.paper_objects import (
    PublicKey, MasterSecret, SigningKey, Signature,
)
from experiments.research.candidates.srgg.paper_parameters import PaperParams


@pytest.fixture(scope="module", params=[(name, interpretation)
    for name in codec.PROFILES for interpretation in codec.INTERPRETATIONS])
def objects(request):
    params = PaperParams(*request.param)
    ring, seed = PaperRing(params), bytes(range(32))
    witness = [[ring.constant(0) for _ in range(params.rank*params.digits)]
               for _ in range(2*params.rank)]
    witness[0][0] = tuple([-1, 0, 1]+[0]*(params.degree-3))
    witness = tuple(tuple(row) for row in witness)
    a_hat = public_matrix(params, seed)
    public = PublicKey(params, seed, a_hat, ring.build_public(a_hat, witness))
    tail = [ring.constant(0)]*((1+params.digits)*params.rank)
    tail[0] = tuple([0, -1, 1, -1025, 1024]+[0]*(params.degree-5))
    key = SigningKey(public, b"codec-algebra-fixture", tuple(tail))
    master = MasterSecret(public, witness, {key.identity: ("issued", key),
        b"failed": ("failed", None), b"pending": ("pending", None)})
    response = [ring.constant(0)]*(params.columns+1)
    response[0] = tuple([0, -1, 1, -32769, 32768]+[0]*(params.degree-5))
    signature = Signature(public.context, tuple(response), tuple(i % 2 for i in range(params.degree)))
    return public, master, key, signature


def _methods(objects):
    public, master, key, signature = objects
    return ((public, codec.dump_public, codec.load_public),
        (master, codec.dump_master, lambda data: codec.load_master(data, public)),
        (key, codec.dump_key, lambda data: codec.load_key(data, public)),
        (signature, lambda value: codec.dump_signature(public, value),
         lambda data: codec.load_signature(public, data)))


def test_four_objects_losslessly_roundtrip_preserving_original_json_context(objects):
    for value, dump, load in _methods(objects):
        original_json = value.to_bytes()
        data = dump(value)
        restored = load(data)
        assert restored.to_bytes() == original_json
        assert dump(restored) == data
        # Sparse public fixtures can be shorter as JSON; compression is a
        # measured lifecycle result, never a promise for every valid object.
        assert len(data) <= codec.MAX_WIRE
    public, master, key, _ = objects
    restored = codec.load_master(codec.dump_master(master), public)
    assert restored.public_key.context == public.context
    assert restored.states[key.identity][1].full == key.full
    assert set(restored.states) == set(master.states)
    assert codec.dump_master(replace(master, states=dict(reversed(tuple(master.states.items()))))) == codec.dump_master(master)


@pytest.mark.parametrize("object_position", range(4))
def test_wrong_magic_version_kind_source_profile_truncation_and_append(objects, object_position):
    value, dump, load = _methods(objects)[object_position]
    data = dump(value)
    variants = [b"", data[:1], data[:-1], data+b"\0", bytearray(data), memoryview(data)]
    for offset, replacement in ((0, 0), (len(codec.MAGIC), 2),
            (len(codec.MAGIC)+1, 255), (len(codec.MAGIC)+2, 0),
            (len(codec.MAGIC)+3, 0), (codec.HEADER_BYTES-1, data[codec.HEADER_BYTES-1] ^ 1)):
        altered = bytearray(data)
        altered[offset] = replacement
        variants.append(bytes(altered))
    for malformed in variants:
        with pytest.raises(SerializationError):
            load(malformed)


def test_public_coefficients_are_unsigned_mod_Q_without_reduction(objects):
    public, _, _, _ = objects
    data = codec.dump_public(public)
    offset = codec.HEADER_BYTES+32
    for value in (public.params.modulus, (1 << 24)-1):
        altered = data[:offset]+value.to_bytes(3, "big")+data[offset+3:]
        with pytest.raises(SerializationError, match="public residue"):
            codec.load_public(altered)


def test_embedded_public_expected_binding_and_outer_profile_rejected(objects):
    public, master, key, _ = objects
    changed = [list(row) for row in public.b]
    changed[0][0] = tuple([(changed[0][0][0]+1) % public.params.modulus]+list(changed[0][0][1:]))
    other = replace(public, b=changed)
    for value, dump, load in ((key, codec.dump_key, codec.load_key),
                              (master, codec.dump_master, codec.load_master)):
        data = dump(value)
        with pytest.raises(SerializationError, match="expected public"):
            load(data, other)
        altered = bytearray(data)
        altered[len(codec.MAGIC)+2] = (codec.PROFILES.index(public.params.profile_name)+1) % 3+1
        with pytest.raises(SerializationError, match="parameter mismatch"):
            load(bytes(altered))


def test_cbd1_invalid_code_and_wrong_trapdoor_rejected(objects):
    public, master, _, _ = objects
    data = codec.dump_master(master)
    offset = codec.HEADER_BYTES+codec._public_size(public.params)
    for code in (3, 1):
        altered = bytearray(data)
        altered[offset] = (altered[offset] & 63) | (code << 6)
        with pytest.raises(SerializationError):
            codec.load_master(bytes(altered))


def test_minimal_signed_width_zero_negative_and_exact_256bit_extremes(objects):
    public, _, key, signature = objects
    ring = PaperRing(public.params)
    boundary = (1 << 256)-1
    for value in (0, -1, 1, -boundary, boundary):
        tail = (ring.constant(value),)+(ring.constant(0),)*(len(key.tail)-1)
        altered_key = replace(key, tail=tail)
        assert codec.load_key(codec.dump_key(altered_key), public).tail == altered_key.tail
        response = (ring.constant(value),)+(ring.constant(0),)*(len(signature.response)-1)
        altered_sig = replace(signature, response=response)
        assert codec.load_signature(public, codec.dump_signature(public, altered_sig)).response == response
    zero_sig = replace(signature, response=(ring.constant(0),)*len(signature.response))
    encoded = codec.dump_signature(public, zero_sig)
    offset = codec.HEADER_BYTES+32
    assert encoded[offset:offset+2] == b"\0\0"
    # Same all-zero vector at width 1 is a distinct, forbidden representation.
    nonminimal = encoded[:offset]+b"\0\1"+bytes(len(signature.response)*public.params.degree//8)+encoded[offset+2:]
    with pytest.raises(SerializationError, match="nonminimal"):
        codec.load_signature(public, nonminimal)
    with pytest.raises(SerializationError, match="width"):
        codec.load_signature(public, encoded[:offset]+(258).to_bytes(2, "big")+encoded[offset+2:])
    # Zigzag 2^257-1 would decode to -2^256, outside the existing object domain.
    invalid = encoded[:offset]+(257).to_bytes(2, "big")+pack(
        ((1 << 257)-1,)+(0,)*(len(signature.response)*public.params.degree-1), 257)+encoded[offset+2:]
    with pytest.raises(SerializationError, match="signed coefficient"):
        codec.load_signature(public, invalid)


def test_signature_keeps_json_context_and_rejects_wrong_public_or_dimensions(objects):
    public, _, _, signature = objects
    data = codec.dump_signature(public, signature)
    corrupted = bytearray(data)
    corrupted[codec.HEADER_BYTES] ^= 1
    with pytest.raises(SerializationError, match="signature public"):
        codec.load_signature(public, bytes(corrupted))
    wrong = replace(public, seed=bytes(reversed(public.seed)),
                    a_hat=public_matrix(public.params, bytes(reversed(public.seed))))
    with pytest.raises(SerializationError):
        codec.load_signature(wrong, data)
    with pytest.raises(ValueError):
        codec.dump_signature(public, replace(signature, response=signature.response[:-1]))
    with pytest.raises(SerializationError):
        codec.dump_signature(public, replace(signature, context=bytes(32)))


def test_master_count_status_order_and_identity_caps(objects):
    public, master, _, _ = objects
    empty = replace(master, states={})
    data = codec.dump_master(empty)
    count_offset = len(data)-1
    with pytest.raises(SerializationError, match="capacity"):
        codec.load_master(data[:-1]+bytes((65,)))
    for size in (0, 4097, 65535):
        malformed = data[:-1]+b"\1"+size.to_bytes(2, "big")
        with pytest.raises(SerializationError, match="identity length"):
            codec.load_master(malformed)
    for suffix in (b"\1\0\1x\3", b"\2\0\1x\0\0\1x\0",
                   b"\2\0\1z\0\0\1a\0"):
        with pytest.raises(SerializationError):
            codec.load_master(data[:count_offset]+suffix)
    boundary = replace(master, states={bytes((i+1,)): ("pending", None) for i in range(64)})
    assert len(codec.load_master(codec.dump_master(boundary), public).states) == 64
    long_identity = b"i"*4096
    boundary = replace(master, states={long_identity: ("failed", None)})
    assert tuple(codec.load_master(codec.dump_master(boundary)).states) == (long_identity,)


def test_wire_capacity_rejected_before_parsing(objects, monkeypatch):
    public, _, _, _ = objects
    def forbidden(*_args, **_kwargs):
        raise AssertionError("oversized wire reached parser")
    monkeypatch.setattr(codec, "_read_header", forbidden)
    for load in (codec.load_public, codec.load_key, codec.load_master,
                 lambda data: codec.load_signature(public, data)):
        with pytest.raises(SerializationError, match="bounded compact"):
            load(bytes(codec.MAX_WIRE+1))


def test_output_capacity_is_enforced_incrementally(objects, monkeypatch):
    for value, dump, _load in _methods(objects):
        capacity = len(dump(value))
        with monkeypatch.context() as patch:
            patch.setattr(codec, "MAX_WIRE", capacity-1)
            with pytest.raises(SerializationError, match="wire capacity"):
                dump(value)


def test_truncated_large_width_rejected_before_coefficients_are_allocated(objects, monkeypatch):
    public, _, _, signature = objects
    data = codec.dump_signature(public, signature)
    offset = codec.HEADER_BYTES+32
    def forbidden(*_args, **_kwargs):
        raise AssertionError("truncated bit field reached allocation")
    monkeypatch.setattr(codec, "unpack", forbidden)
    with pytest.raises(SerializationError, match="truncated"):
        codec.load_signature(public, data[:offset]+(257).to_bytes(2, "big"))


@pytest.mark.parametrize("width,values,expected", [
    (0, (0, 0, 0), b""), (1, (1, 0, 1), b"\xa0"),
    (2, (0, 1, 2), b"\x18"), (9, (1, 511), b"\0\xff\xc0"),
    (24, (0, 15744062), b"\0\0\0\xf0\x3c\x3e"),
])
def test_msb_first_known_fields_and_zero_padding(width, values, expected):
    assert pack(values, width) == expected
    assert unpack(expected, len(values), width) == values
    padding = (-len(values)*width) % 8
    if padding:
        with pytest.raises(SerializationError, match="padding"):
            unpack(expected[:-1]+bytes((expected[-1] | 1,)), len(values), width)


@pytest.mark.parametrize("values,width", [((-1,), 1), ((2,), 1), ((True,), 1), ((0,), 258)])
def test_bit_field_range_checks(values, width):
    with pytest.raises(SerializationError):
        pack(values, width)


def test_bit_field_declared_length_is_checked_before_allocation():
    for data, count, width in ((b"", 512, 257), (b"\0", 512, 1), (b"\0", 0, 0)):
        with pytest.raises(SerializationError):
            unpack(data, count, width)
